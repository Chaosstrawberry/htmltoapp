export function buildMd(config: AppConfig): string {
  const hasWin = config.targets.windows.length > 0
  const hasLinux = config.targets.linux.length > 0
  const hasMac = config.targets.mac.length > 0

  const sections: string[] = []

  sections.push(`# Build instructions — ${config.name}

This document explains, step by step, how to turn this project into native
applications and installers on each platform.

## Prerequisites (all platforms)

- Install [Node.js](https://nodejs.org/) 18+ (includes npm).
- Keep an internet connection available for the first build.
`)

  if (hasWin) {
    sections.push(`## Windows

1. Extract the ZIP.
2. Open the extracted folder.
3. Double-click **\`build.bat\`** (or run \`scripts\\build-windows.bat\`).
4. Wait for the build to finish — dependencies install automatically.
5. Open the **\`dist\\\`** folder.
6. Run the produced installer or portable executable.

${
  config.targets.windows.includes('portable')
    ? 'For only the portable build, run `scripts\\build-portable.bat`.\n'
    : ''
}`)
  }

  if (hasLinux) {
    sections.push(`## Linux

1. Open a terminal in the extracted folder.
2. Make the script executable: \`chmod +x build.sh scripts/build-linux.sh\`
3. Run \`./scripts/build-linux.sh\` (or \`./build.sh\`).
4. Find the output (\`.AppImage\`, \`.deb\`, \`.rpm\`) in **\`dist/\`**.

> Building \`.deb\`/\`.rpm\` works most reliably on a Linux host. AppImage runs on
> most distributions without installation.
`)
  }

  if (hasMac) {
    sections.push(`## macOS

1. Open a terminal in the extracted folder.
2. Make the script executable: \`chmod +x build.sh scripts/build-macos.sh\`
3. Run \`./scripts/build-macos.sh\` (or \`./build.sh\`).
4. Find the \`.dmg\` / \`.app\` in **\`dist/\`**.

> macOS applications **must be built on macOS**. For distribution outside your
> own machine you must code-sign and notarize the app with an Apple Developer ID.
`)
  }

  sections.push(`## What the build produces

The \`electron-builder\` configuration in \`package.json\` defines the targets you
selected. Change the \`build\` section there to add or remove targets later
without regenerating the project.

## Cleaning

Delete the \`dist/\` and \`node_modules/\` folders to reset. The next build will
reinstall dependencies automatically.
`)

  return sections.join('\n')
}
