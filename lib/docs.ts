import type { AppConfig } from './types'

function targetSummary(config: AppConfig): string[] {
  const lines: string[] = []
  const win = config.targets.windows
  const lin = config.targets.linux
  const mac = config.targets.mac
  if (win.includes('nsis')) lines.push('- Windows — NSIS installer (`Setup.exe`)')
  if (win.includes('portable')) lines.push('- Windows — Portable executable')
  if (lin.includes('appimage')) lines.push('- Linux — AppImage')
  if (lin.includes('deb')) lines.push('- Linux — Debian package (`.deb`)')
  if (lin.includes('rpm')) lines.push('- Linux — RPM package (`.rpm`)')
  if (mac.includes('dmg')) lines.push('- macOS — DMG disk image')
  if (mac.includes('zip')) lines.push('- macOS — Zipped `.app` bundle')
  return lines
}

